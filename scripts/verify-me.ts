/**
 * Writes VERIFY_ME.md from the contact files in src/data/help/.
 *
 *   npm run verify-me
 *
 * The site owner uses it as a checklist. A unit test fails if the file is
 * out of date, so it always matches the data.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseHelpFile, type HelpEntry, type HelpFile } from '../src/data/help-schema';

const HELP_DIR = 'src/data/help';
export const VERIFY_ME_PATH = 'VERIFY_ME.md';

export function loadHelpFiles(dir = HELP_DIR): HelpFile[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => parseHelpFile(JSON.parse(readFileSync(join(dir, f), 'utf8')), f));
}

const COUNTRY_NAMES: Record<string, string> = {
  CD: 'Democratic Republic of the Congo',
  UG: 'Uganda',
  KE: 'Kenya',
  NG: 'Nigeria',
  RW: 'Rwanda',
};

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function what(entry: HelpEntry): string {
  switch (entry.kind) {
    case 'phone':
      return `${entry.purpose.replace('-', ' ')} (${entry.channel}${entry.free ? ', free' : ''})`;
    case 'office':
      return `${entry.role === 'who' ? 'WHO country office' : entry.role} contact`;
    case 'facility':
      return `${entry.facilityType.replace('-', ' ')}`;
  }
}

function detail(entry: HelpEntry): string {
  switch (entry.kind) {
    case 'phone':
      return `**${entry.display ?? entry.number}**`;
    case 'office':
      return [entry.address, entry.phones?.join(', '), entry.email, entry.website].filter(Boolean).join(' · ');
    case 'facility':
      return [entry.name, entry.place, entry.province].filter(Boolean).join(', ');
  }
}

export function renderVerifyMe(files: HelpFile[]): string {
  const lines: string[] = [];
  const all = files.flatMap((f) => f.entries);
  const pending = all.filter((e) => e.status === 'pending').length;
  const verified = all.filter((e) => e.status === 'verified').length;

  lines.push(
    '# Contact details waiting for your check',
    '',
    '<!-- This file is generated by `npm run verify-me` from src/data/help/*.json. Do not edit by hand. -->',
    '',
    `**${pending} waiting** · ${verified} confirmed and shown on the site.`,
    '',
    'Nothing marked ⏳ appears on the website. A detail is published only after',
    'you have checked it against the official source.',
    '',
    '## How to check an entry',
    '',
    '1. Open the link under "Where it was found".',
    '2. Find the text quoted under "Text on the page" (Ctrl+F or "Find in page").',
    '3. Check that the number or address is exactly the same, digit by digit.',
    '4. On the editing page (app.pagescms.org → Helplines and contacts → the',
    '   country), open the entry, set **Status** to "Verified" and **Date I',
    '   verified it** to today, then Save. If a detail is wrong, choose "Rejected".',
    '   Or simply tell Claude which entries match (for example "cd-numero-vert-151 OK").',
    '',
    'This list updates itself a few minutes after each save.',
    '',
    'Entries marked ⚠️ were found only in news reports or on pages our servers',
    'could not open. Please check them on an official website or the official',
    "social-media account of the ministry before confirming.",
    '',
  );

  for (const file of files) {
    lines.push(`## ${COUNTRY_NAMES[file.country] ?? file.country} (\`src/data/help/${file.country}.json\`)`, '');
    lines.push('| Status | Id | What | Detail | Where it was found | Text on the page | Found on |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const entry of file.entries) {
      const status =
        entry.status === 'verified' ? `✅ ${entry.verifiedAt}` : entry.status === 'rejected' ? '❌ rejected' : entry.ownerNote ? '⏳ ⚠️' : '⏳';
      lines.push(
        `| ${status} | \`${entry.id}\` | ${cell(what(entry))} | ${cell(detail(entry))} | [${cell(entry.sourceTitle)}](${entry.sourceUrl}) | “${cell(entry.sourceQuote)}” | ${entry.foundOn} |`,
      );
    }
    const notes = file.entries.filter((e) => e.ownerNote);
    if (notes.length > 0 || file.facilityNote) {
      lines.push('', '**Notes**', '');
      for (const e of notes) lines.push(`- \`${e.id}\`: ${e.ownerNote}`);
      if (file.facilityNote) lines.push(`- Treatment centres: ${file.facilityNote}`);
    }
    lines.push('');
  }

  lines.push(
    '## Not included',
    '',
    '- **General emergency numbers** (police, ambulance) were not added: no official',
    '  source listing them was found during this check.',
    '- **Treatment centres:** no official public list with addresses was found for',
    '  any country. Hotlines direct people to the right centre.',
    '- **Other countries** can be added on request, with the same checks.',
    '',
  );
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(VERIFY_ME_PATH, renderVerifyMe(loadHelpFiles()));
  console.log(`Wrote ${VERIFY_ME_PATH}.`);
}
